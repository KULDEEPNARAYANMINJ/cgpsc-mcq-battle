// --- APP STATE ---
let userName = "";
let battleQuestions = [];
let currentQuestionIndex = 0;
let score = 0;
let battleTimer;
let totalTime = 180; // 3 minutes in seconds
let isBattleActive = false;

// --- DOM ELEMENTS ---
const screens = {
    register: document.getElementById('screen-register'),
    lobby: document.getElementById('screen-lobby'),
    battle: document.getElementById('screen-battle'),
    result: document.getElementById('screen-result')
};

// --- NAVIGATION ---
function showScreen(screenName) {
    Object.values(screens).forEach(screen => {
        screen.classList.remove('active');
        setTimeout(() => screen.classList.add('hidden'), 400); 
    });
    
    setTimeout(() => {
        screens[screenName].classList.remove('hidden');
        setTimeout(() => screens[screenName].classList.add('active'), 50);
    }, 400);
}

// --- 1. REGISTRATION ---
function registerUser() {
    const input = document.getElementById('username').value.trim();
    if (!input) {
        alert("Enter your name to join the battle!");
        return;
    }
    userName = input;
    document.getElementById('display-name').innerText = userName;
    document.getElementById('user-info').classList.remove('hidden');
    
    showScreen('lobby');
    startLobbyCountdown();
}

// --- 2. LOBBY & COUNTDOWN TO 10:00 AM ---
function startLobbyCountdown() {
    const countdownEl = document.getElementById('countdown');
    const startBtn = document.getElementById('btn-start-battle');

    setInterval(() => {
        const now = new Date();
        let target = new Date();
        target.setHours(10, 0, 0, 0);

        // If it's past 10:05 AM, set target to tomorrow 10 AM
        if (now.getHours() >= 10 && (now.getHours() > 10 || now.getMinutes() >= 5)) {
            target.setDate(target.getDate() + 1);
        }

        const diff = target - now;

        // 5-minute active window: 10:00 AM to 10:04:59 AM
        if (now.getHours() === 10 && now.getMinutes() < 5) {
            countdownEl.innerText = "BATTLE IS LIVE!";
            countdownEl.classList.add('text-green-400');
            startBtn.disabled = false;
            startBtn.classList.remove('bg-gray-600', 'cursor-not-allowed');
            startBtn.classList.add('bg-gradient-to-r', 'from-green-500', 'to-green-700', 'hover:from-green-400', 'hover:to-green-600');
            startBtn.innerText = "ENTER BATTLE NOW";
            return;
        }

        const h = Math.floor((diff % (1000 * 60 * 60 * 24)) / (1000 * 60 * 60));
        const m = Math.floor((diff % (1000 * 60 * 60)) / (1000 * 60));
        const s = Math.floor((diff % (1000 * 60)) / 1000);

        countdownEl.innerText = 
            `${h.toString().padStart(2, '0')}:${m.toString().padStart(2, '0')}:${s.toString().padStart(2, '0')}`;
    }, 1000);
}

// --- 3. BATTLE LOGIC ---
function startBattle() {
    // Pick up to 20 random questions from the bank
    let shuffled = [...questionBank].sort(() => 0.5 - Math.random());
    battleQuestions = shuffled.slice(0, 20);
    
    // Reset state
    currentQuestionIndex = 0;
    score = 0;
    totalTime = 180; 
    isBattleActive = true;

    // Transition UI
    showScreen('battle');
    loadQuestion();
    startBattleTimer();
}

function startBattleTimer() {
    const timeEl = document.getElementById('time-left');
    const timerBar = document.getElementById('timer-bar');

    battleTimer = setInterval(() => {
        if (totalTime <= 0) {
            clearInterval(battleTimer);
            endBattle();
            return;
        }
        
        totalTime--;
        
        // Update Time Text
        const m = Math.floor(totalTime / 60);
        const s = totalTime % 60;
        timeEl.innerText = `${m.toString().padStart(2, '0')}:${s.toString().padStart(2, '0')}`;
        
        // Update Progress Bar
        const percentage = (totalTime / 180) * 100;
        timerBar.style.width = `${percentage}%`;

        // Low time alert
        if(totalTime < 30) {
            timeEl.classList.add('animate-pulse', 'text-red-500');
        }

    }, 1000);
}

function loadQuestion() {
    if (currentQuestionIndex >= battleQuestions.length) {
        endBattle();
        return;
    }

    const qData = battleQuestions[currentQuestionIndex];
    document.getElementById('q-current').innerText = currentQuestionIndex + 1;
    document.getElementById('question-text').innerText = qData.q;
    
    const optionsContainer = document.getElementById('options-container');
    optionsContainer.innerHTML = ''; 

    qData.options.forEach((opt, index) => {
        const btn = document.createElement('button');
        btn.className = "option-btn w-full text-left p-4 bg-gray-700 rounded-lg text-lg font-medium shadow-sm hover:shadow-md mb-3";
        btn.innerText = opt;
        btn.onclick = () => handleAnswer(index, btn);
        optionsContainer.appendChild(btn);
    });
}

function handleAnswer(selectedIndex, btnElement) {
    if (!isBattleActive) return;
    
    const qData = battleQuestions[currentQuestionIndex];
    const isCorrect = (selectedIndex === qData.ans);
    
    // Lock all buttons
    const allButtons = document.querySelectorAll('.option-btn');
    allButtons.forEach(b => b.onclick = null);

    if (isCorrect) {
        btnElement.classList.add('correct');
        score++;
    } else {
        btnElement.classList.add('wrong');
        // Highlight correct answer
        allButtons[qData.ans].classList.add('correct');
    }

    // Auto-advance after 1.2 seconds
    setTimeout(() => {
        currentQuestionIndex++;
        loadQuestion();
    }, 1200);
}

// --- 4. END RESULT ---
function endBattle() {
    isBattleActive = false;
    clearInterval(battleTimer);
    document.getElementById('final-score').innerText = score;
    showScreen('result');
}
